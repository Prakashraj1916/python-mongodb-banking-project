import { useEffect, useState } from "react";
import { useNavigate, useLocation } from "react-router-dom";
import API from "../../service/api";
import "../../App.css";

function CustomerCollection() {

    const navigate = useNavigate();
    const location = useLocation();


    const [generatedAccountId, setGeneratedAccountId] = useState("");

    const [formData, setFormData] = useState({
        name: "",
        age: "",
        account_type: "",
        balance: ""
    });

    useEffect(() => {
        const customerData = location.state?.customerData;

        if (customerData) {
            setFormData((previousData) => ({
                ...previousData,
                name: customerData.name || "",
                age: customerData.age
                    ? String(customerData.age)
                    : "",
                account_type: customerData.account_type || "",
                balance: customerData.balance !== undefined && customerData.balance !== null
                    ? String(customerData.balance)
                    : previousData.balance
            }));
        }
    }, [location.state]);
    
    // Get the next Account ID when the page loads
    useEffect(() => {
        getNextAccountId();
    }, []);

    const getNextAccountId = async () => {
        try {

            const response = await API.get(
                "/customers/next-account-id"
            );

            console.log(
                "Next Account ID:",
                response.data
            );

            setGeneratedAccountId(
                response.data.account_id
            );

        } catch (error) {

            console.log(
                "Account ID fetch error:",
                error
            );

            alert(
                error.response?.data?.detail ||
                "Failed to generate Account ID"
            );
        }
    };

    const handleChange = (e) => {

        setFormData({
            ...formData,
            [e.target.name]: e.target.value
        });

    };

    const handleSubmit = async (e) => {

        e.preventDefault();

        try {

            const customerData = {
                name: formData.name,
                age: Number(formData.age),
                account_type: formData.account_type,
                balance: Number(formData.balance)
            };

            console.log(
                "Customer data being sent:",
                customerData
            );

            const response = await API.post(
                "/customers/posting",
                customerData
            );

            console.log(
                "Customer response:",
                response.data
            );

            // Get the actual Account ID generated by backend
            const accountId = response.data.account_id;

            console.log(
                "Account ID received:",
                accountId
            );

            if (!accountId) {

                alert(
                    "Account ID was not returned from backend."
                );

                return;
            }

            alert(
                `Customer added successfully!\nAccount ID: ${accountId}`
            );

            // Navigate to Personal Details
            navigate(
                `/collection/personal/${accountId}`
            );

        } catch (error) {

            console.log(
                "Customer submission error:",
                error
            );

            if (error.response) {

                console.log(
                    "Backend error:",
                    error.response.data
                );

                alert(
                    "Error " +
                    error.response.status +
                    ": " +
                    JSON.stringify(
                        error.response.data
                    )
                );

            } else {

                alert(
                    "Request failed: " +
                    error.message
                );

            }
        }
    };

    return (
        <div className="collection-page">

            <div className="collection-card">

                <div className="collection-header">

                    <h2>Customer Collection</h2>

                    <p>
                        Enter customer details
                    </p>

                </div>


                <form onSubmit={handleSubmit}>

                    <div className="customer-grid">
                        
                        {/* Name */}

                        <div className="input-group">

                            <label>
                                Name
                            </label>

                            <input
                                type="text"
                                name="name"
                                value={formData.name}
                                onChange={handleChange}
                                placeholder="Enter Name"
                                required
                            />

                        </div>


                        {/* Age */}

                        <div className="input-group">

                            <label>
                                Age
                            </label>

                            <input
                                type="number"
                                name="age"
                                value={formData.age}
                                onChange={handleChange}
                                min="1"
                                max="99"
                                placeholder="Enter Age"
                                required
                            />

                        </div>


                        {/* Account Type */}

                        <div className="input-group">

                            <label>
                                Account Type
                            </label>

                            <select
                                name="account_type"
                                value={formData.account_type}
                                onChange={handleChange}
                                required
                            >

                                <option value="">
                                    Select Account Type
                                </option>

                                <option value="Savings">
                                    Savings
                                </option>

                                <option value="Current">
                                    Current
                                </option>

                                <option value="Salary">
                                    Salary
                                </option>

                            </select>

                        </div>


                        {/* Balance */}

                        <div className="input-group">

                            <label>
                                Balance
                            </label>

                            <input
                                type="number"
                                name="balance"
                                value={formData.balance}
                                onChange={handleChange}
                                placeholder="Enter Balance"
                                required
                            />

                        </div>

                    </div>


                    {/* Button */}

                    <div className="form-buttons">

                        <button
                            type="submit"
                            className="add-customer-button"
                        >
                            Add Customer
                        </button>

                    </div>

                </form>

            </div>

        </div>
    );
}

export default CustomerCollection;